def predict_traffic(input_24_hours):

    input_array = np.asarray(
        input_24_hours,
        dtype=np.float32
    )

    if input_array.shape != (24, 20):
        raise ValueError(
            f"Expected input shape (24, 20), "
            f"but received {input_array.shape}"
        )

    input_scaled = feature_scaler.transform(
        input_array
    )

    input_sequence = np.expand_dims(
        input_scaled,
        axis=0
    )

    prediction_scaled = model.predict(
        input_sequence,
        verbose=0
    )

    prediction = target_scaler.inverse_transform(
        prediction_scaled
    )

    return float(prediction[0, 0])


