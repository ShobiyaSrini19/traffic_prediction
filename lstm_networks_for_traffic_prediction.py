# STEP 25 — Create valid LSTM sequences

import numpy as np

SEQUENCE_LENGTH = 24


def create_sequences(X_data, y_data, dates, sequence_length=24):
    X_sequences = []
    y_sequences = []

    for i in range(sequence_length, len(X_data)):

        # Check whether the entire sequence is hourly and continuous
        time_window = dates.iloc[i-sequence_length:i+1]
        time_differences = time_window.diff().dropna()

        # Every consecutive observation must be exactly 1 hour apart
        if (time_differences == pd.Timedelta(hours=1)).all():
            X_sequences.append(
                X_data[i-sequence_length:i]
            )
            y_sequences.append(
                y_data[i]
            )

    return np.array(X_sequences), np.array(y_sequences)


